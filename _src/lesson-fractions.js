/* ابزارهای کوچک برای کشیدن کیک و نان (SVG) */
var fr = function (n, d) { return '<span class="fr"><b>' + n + '</b><i>' + d + '</i></span>'; };
var CAKE = '#f7b7c8', CAKE_ON = '#e2457a', LINE = '#7a2945';
function pie(parts, shaded, size, ids) {
  size = size || 150; var r = size / 2 - 6, c = size / 2, out = '';
  var set = typeof shaded === 'number' ? function (k) { return k < shaded; } : function (k) { return shaded.indexOf(k) >= 0; };
  if (parts === 1) out = '<circle cx="' + c + '" cy="' + c + '" r="' + r + '" fill="' + (set(0) ? CAKE_ON : CAKE) + '" stroke="' + LINE + '" stroke-width="3"/>';
  else for (var k = 0; k < parts; k++) {
    var a0 = (k / parts) * 2 * Math.PI - Math.PI / 2, a1 = ((k + 1) / parts) * 2 * Math.PI - Math.PI / 2;
    var x0 = c + r * Math.cos(a0), y0 = c + r * Math.sin(a0), x1 = c + r * Math.cos(a1), y1 = c + r * Math.sin(a1);
    out += '<path ' + (ids ? 'data-k="' + k + '" style="cursor:pointer" ' : '') + 'd="M' + c + ' ' + c + ' L' + x0.toFixed(2) + ' ' + y0.toFixed(2) + ' A' + r + ' ' + r + ' 0 ' + (parts === 2 ? 0 : 0) + ' 1 ' + x1.toFixed(2) + ' ' + y1.toFixed(2) + ' Z" fill="' + (set(k) ? CAKE_ON : CAKE) + '" stroke="' + LINE + '" stroke-width="3" stroke-linejoin="round"/>';
  }
  return '<svg viewBox="0 0 ' + size + ' ' + size + '" width="' + size + '" height="' + size + '" role="img">' + out + '</svg>';
}
function bar(parts, shaded, w, ids, faded) {
  w = w || 300; var hgt = 60, pw = (w - 8) / parts, out = '';
  var set = typeof shaded === 'number' ? function (k) { return k < shaded; } : function (k) { return shaded.indexOf(k) >= 0; };
  for (var k = 0; k < parts; k++) {
    var x = 4 + (parts - 1 - k) * pw; // از راست به چپ
    var fade = faded && faded.indexOf(k) >= 0;
    out += '<rect ' + (ids ? 'data-k="' + k + '" style="cursor:pointer" ' : '') + 'x="' + x.toFixed(1) + '" y="4" width="' + pw.toFixed(1) + '" height="' + hgt + '" rx="4" fill="' + (set(k) ? '#d98b3a' : '#f6d6a8') + '" stroke="#7a4b17" stroke-width="3"' + (fade ? ' opacity=".25" stroke-dasharray="6 5"' : '') + '/>';
  }
  return '<svg viewBox="0 0 ' + w + ' 68" width="' + w + '" height="68" role="img">' + out + '</svg>';
}
function unequalBar(w) {
  w = w || 240; var xs = [4, 40, 110, 150, w - 4], out = '';
  for (var k = 0; k < 4; k++) out += '<rect x="' + xs[k] + '" y="4" width="' + (xs[k + 1] - xs[k]) + '" height="56" rx="4" fill="' + (k === 0 ? CAKE_ON : CAKE) + '" stroke="' + LINE + '" stroke-width="3"/>';
  return '<svg viewBox="0 0 ' + w + ' 64" width="' + w + '" height="64">' + out + '</svg>';
}
function unequalPie(size) {
  size = size || 130; var c = size / 2, r = c - 6;
  return '<svg viewBox="0 0 ' + size + ' ' + size + '" width="' + size + '" height="' + size + '"><circle cx="' + c + '" cy="' + c + '" r="' + r + '" fill="' + CAKE + '" stroke="' + LINE + '" stroke-width="3"/>' +
    '<line x1="' + c + '" y1="6" x2="' + c + '" y2="' + (size - 6) + '" stroke="' + LINE + '" stroke-width="3"/>' +
    '<line x1="' + c + '" y1="' + (c + 20) + '" x2="' + (size - 6) + '" y2="' + (c + 20) + '" stroke="' + LINE + '" stroke-width="3"/>' +
    '<line x1="6" y1="' + (c - 25) + '" x2="' + c + '" y2="' + (c - 25) + '" stroke="' + LINE + '" stroke-width="3"/></svg>';
}

/* فعالیت «رنگ‌کن»: دانش‌آموز تکه‌ها را لمس می‌کند تا رنگ شوند */
function shadeTask(rounds) {
  return function (el, api) {
    var st = api.state; st.round = st.round || 0; st.on = st.on || [];
    var wrap = api.h('div', { class: 'center' });
    var title = api.h('p', { class: 'lead' });
    var pic = api.h('div', { class: 'media' });
    var count = api.h('p', { class: 'muted' });
    var chk = api.h('button', { class: 'btn', type: 'button', text: 'بررسی ✓' });
    var clr = api.h('button', { class: 'btn ghost', type: 'button', text: 'پاک کن', onclick: function () { st.on = []; api.save(); draw(); } });
    function draw() {
      var R = rounds[Math.min(st.round, rounds.length - 1)];
      title.innerHTML = (rounds.length > 1 ? '<span class="tag">' + api.fa((st.round + 1) + ' از ' + rounds.length) + '</span> ' : '') + R.say;
      pic.innerHTML = R.shape === 'bar' ? bar(R.parts, st.on, 320, true) : pie(R.parts, st.on, 190, true);
      count.textContent = api.fa('تکه‌های رنگ‌شده: ' + st.on.length + ' از ' + R.parts);
      Array.prototype.forEach.call(pic.querySelectorAll('[data-k]'), function (p) {
        p.addEventListener('click', function () {
          if (api.isDone()) return;
          var k = +p.getAttribute('data-k'), i = st.on.indexOf(k);
          if (i >= 0) st.on.splice(i, 1); else st.on.push(k);
          api.sound('click'); api.save(); draw();
        });
      });
      api.faNodes(title);
    }
    chk.onclick = function () {
      var R = rounds[Math.min(st.round, rounds.length - 1)], n = st.on.length;
      if (n === R.need) {
        if (st.round < rounds.length - 1) { st.round++; st.on = []; api.save(); api.info(R.ok + ' حالا سفارش بعدی 👇'); api.sound('ok'); draw(); }
        else api.right(R.ok);
      } else {
        var m = (R.miss && R.miss[n]) || R.fb || ('تو ' + n + ' تکه رنگ کردی. عدد بالای کسر می‌گوید چند تکه لازم است.');
        api.wrong(m, R.tags && R.tags[n]);
      }
    };
    add2(wrap, [title, pic, count, api.h('div', { class: 'row', style: 'justify-content:center' }, chk, clr)]);
    el.appendChild(wrap);
    draw();
    function add2(p, arr) { arr.forEach(function (x) { p.appendChild(x); }); }
  };
}

