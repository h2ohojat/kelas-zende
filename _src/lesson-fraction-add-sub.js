var fr = function (n, d) { return '<span class="fr"><b>' + n + '</b><i>' + d + '</i></span>'; };

function fracBar(parts, shaded, width, color, faded) {
  width = width || 300;
  color = color || '#2f8f83';
  var hgt = 56, pw = (width - 8) / parts, out = '';
  var set = typeof shaded === 'number' ? function (k) { return k < shaded; } : function (k) { return shaded.indexOf(k) >= 0; };
  faded = faded || [];
  for (var k = 0; k < parts; k++) {
    var x = 4 + (parts - 1 - k) * pw;
    out += '<rect x="' + x.toFixed(2) + '" y="4" width="' + pw.toFixed(2) + '" height="' + hgt + '" rx="3" fill="' +
      (set(k) ? color : '#f5f3ec') + '" stroke="#315c59" stroke-width="2"' +
      (faded.indexOf(k) >= 0 ? ' opacity=".2" stroke-dasharray="5 4"' : '') + '/>';
  }
  return '<svg viewBox="0 0 ' + width + ' 64" width="' + width + '" height="64" role="img" aria-label="' + shaded + ' تکه از ' + parts + ' تکهٔ مساوی">' + out + '</svg>';
}

function equation(left, right) {
  return '<div class="callout center"><span class="big">' + left + ' = ' + right + '</span></div>';
}

/* فعالیت کشفی: دانش‌آموز شبکه‌ای را پیدا می‌کند که نیم و یک‌سوم را هم‌زمان نشان دهد. */
function commonGridTask(el, api) {
  var st = api.state;
  st.parts = st.parts || 2;
  st.seen = st.seen || {};
  var choices = [2, 3, 4, 6, 12];
  var buttons = api.h('div', { class: 'row', style: 'justify-content:center' });
  var picture = api.h('div', { class: 'center media' });
  var message = api.h('div', { class: 'callout' });
  var ask = api.h('div');

  function paint() {
    buttons.innerHTML = '';
    choices.forEach(function (n) {
      var b = api.h('button', { class: 'btn ' + (st.parts === n ? '' : 'ghost'), type: 'button', text: api.fa(n) + ' تکه' });
      b.onclick = function () {
        if (api.isDone()) return;
        st.parts = n; st.seen[n] = 1; api.save(); api.sound('click'); api.emit('grid.try', { parts: n }); paint();
      };
      buttons.appendChild(b);
    });
    var halfOk = st.parts % 2 === 0, thirdOk = st.parts % 3 === 0;
    function measuredBar(value, color, name) {
      var lines = '';
      for (var k = 1; k < st.parts; k++) lines += '<path d="M' + (4 + 332 * k / st.parts) + ' 4v56" stroke="#315c59" stroke-width="2"/>';
      return '<svg viewBox="0 0 340 64" width="340" height="64" role="img" aria-label="' + name + '؛ مقدار ثابت با ' + st.parts + ' قسمت"><rect x="4" y="4" width="332" height="56" fill="#f5f3ec"/><rect x="' + (336 - 332 * value) + '" y="4" width="' + (332 * value) + '" height="56" fill="' + color + '"/>' + lines + '<rect x="4" y="4" width="332" height="56" fill="none" stroke="#315c59" stroke-width="2"/></svg>';
    }
    picture.innerHTML = '<div><b>نصف لیتر</b><br>' + measuredBar(1 / 2, '#f29d49', 'نصف لیتر') + '</div>' +
      '<div><b>یک‌سوم لیتر</b><br>' + measuredBar(1 / 3, '#58a6d6', 'یک‌سوم لیتر') + '</div>';
    if (halfOk && thirdOk) message.innerHTML = '✅ با <b>' + api.fa(st.parts) + ' تکهٔ مساوی</b> می‌توان هر دو مقدار را دقیق ساخت.';
    else if (!halfOk && !thirdOk) message.innerHTML = 'این شبکه نه نصف را دقیق می‌سازد و نه یک‌سوم را. تعداد تکه‌های دیگری را امتحان کن.';
    else message.innerHTML = 'مرز ' + (halfOk ? 'نصف' : 'یک‌سوم') + ' روی خط افتاده، اما مرز ' + (halfOk ? 'یک‌سوم' : 'نصف') + ' داخل یک تکه است. مقدار مایع ثابت مانده؛ شبکهٔ دیگری را امتحان کن.';
    api.faNodes(picture); api.faNodes(message);
  }

  var answers = api.h('div', { class: 'opts cols2' });
  [2, 3, 4, 6, 12].forEach(function (n) {
    var b = api.h('button', { class: 'opt', type: 'button', text: api.fa(n) + ' تکه' });
    b.onclick = function () {
      if (n === 6) {
        b.classList.add('right');
        api.right('دقیقاً! <b>۶ کوچک‌ترین شبکهٔ مشترک</b> است: نصف = ' + fr(3, 6) + ' و یک‌سوم = ' + fr(2, 6) + '. حالا می‌توانیم تکه‌های هم‌اندازه را جمع کنیم.');
      } else if (n === 12) {
        b.classList.add('wrong');
        api.wrong('۱۲ هم جواب می‌دهد، اما پرسش <b>کوچک‌ترین</b> تعداد تکه را می‌خواست. قبل از ۱۲، عدد کوچک‌تری هست که هم بر ۲ و هم بر ۳ بخش‌پذیر است.', 'large-common', { parts: n });
      } else {
        b.classList.add('wrong');
        api.wrong('با ' + api.fa(n) + ' تکه نمی‌توان هم نصف و هم یک‌سوم را با تکه‌های کامل نشان داد. دکمه‌ها را امتحان کن و دنبال نخستین شبکه‌ای بگرد که هر دو نوار را دقیق می‌سازد.', 'common-den', { parts: n });
      }
    };
    answers.appendChild(b);
  });
  ask.appendChild(api.h('h3', { text: 'کوچک‌ترین تعداد تکه‌ای که برای هر دو مقدار مناسب است کدام است؟' }));
  ask.appendChild(answers);
  el.appendChild(api.h('p', { text: 'دکمه‌ها را امتحان کن. هدف این است که «نصف» و «یک‌سوم» را با تکه‌هایی دقیقاً هم‌اندازه بسازیم.' }));
  el.appendChild(buttons); el.appendChild(picture); el.appendChild(message); el.appendChild(ask);
  st.seen[st.parts] = 1; paint();
}

/* فعالیت دست‌ورزی تفریق: از ۹/۱۲ مخزن، دو تکهٔ دوازدهم بیرون ریخته می‌شود. */
function pourTask(el, api) {
  var st = api.state;
  st.removed = st.removed || [];
  var tray = api.h('div', { class: 'center' });
  var count = api.h('p', { class: 'center lead' });
  var check = api.h('button', { class: 'btn', type: 'button', text: 'بررسی کن ✓' });
  var reset = api.h('button', { class: 'btn ghost', type: 'button', text: 'مایع را برگردان' });

  function draw() {
    tray.innerHTML = '';
    var grid = api.h('div', { style: 'display:grid;grid-template-columns:repeat(6,minmax(38px,1fr));gap:6px;max-width:560px;margin:12px auto' });
    for (var k = 0; k < 12; k++) (function (i) {
      var filled = i < 9, gone = st.removed.indexOf(i) >= 0;
      var b = api.h('button', { class: 'item', type: 'button', style: 'min-height:54px;background:' + (filled && !gone ? '#e7794f' : '#f5f3ec') + ';opacity:' + (gone ? '.3' : '1'),
        text: filled ? (gone ? '💧 بیرون' : '🧃') : 'خالی' });
      b.disabled = !filled || api.isDone();
      b.onclick = function () {
        var p = st.removed.indexOf(i);
        if (p >= 0) st.removed.splice(p, 1); else st.removed.push(i);
        api.save(); api.sound('click'); draw();
      };
      grid.appendChild(b);
    })(k);
    tray.appendChild(grid);
    count.textContent = api.fa('بیرون ریخته: ' + st.removed.length + ' تکه از ۱۲ · باقی‌مانده: ' + (9 - st.removed.length) + ' تکه از ۱۲');
  }
  check.onclick = function () {
    if (st.removed.length === 2) api.right('آفرین! ' + fr(3, 4) + ' را به ' + fr(9, 12) + ' و ' + fr(1, 6) + ' را به ' + fr(2, 12) + ' تبدیل کردی؛ پس ' + fr(9, 12) + ' − ' + fr(2, 12) + ' = ' + fr(7, 12) + '.');
    else if (st.removed.length === 1) api.wrong('فقط یک دوازدهم بیرون ریختی. اما ' + fr(1, 6) + ' در شبکهٔ ۱۲تایی چند تکه می‌شود؟', 'scale-both', { removed: 1 });
    else api.wrong('قرار بود به اندازهٔ ' + fr(1, 6) + ' بیرون بریزی. اول یک‌ششم را به دوازدهم تبدیل کن، بعد همان تعداد تکه را لمس کن.', 'remove-amount', { removed: st.removed.length });
  };
  reset.onclick = function () { if (api.isDone()) return; st.removed = []; api.save(); draw(); };
  el.appendChild(api.h('p', { html: 'مخزن ' + fr(3, 4) + ' لیتر نوشیدنی دارد. چون شبکه ۱۲تایی است، این مقدار را به شکل ' + fr(9, 12) + ' می‌بینی. حالا روی مقدار ' + fr(1, 6) + ' لیتر بزن تا آن را بیرون بریزی.' }));
  el.appendChild(tray); el.appendChild(count);
  el.appendChild(api.h('div', { class: 'row', style: 'justify-content:center' }, check, reset));
  draw();
}

